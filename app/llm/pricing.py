"""Cost of a call.

Preferred source: the provider's own `usage.cost` (OpenRouter can report it). Fallback: the static
price table in pricing.json (per-token USD, generated by `python -m app.cli.fetch_pricing`), since
the graders' gateway may not return a cost field.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

PRICING_PATH = Path(__file__).with_name("pricing.json")


@dataclass(frozen=True)
class ModelPrice:
    prompt: float                         # USD per input token
    completion: float                     # USD per output token
    input_cache_read: float | None = None  # USD per provider-cached input token


@lru_cache(maxsize=1)
def load_prices() -> dict[str, ModelPrice]:
    if not PRICING_PATH.exists():
        return {}
    data = json.loads(PRICING_PATH.read_text(encoding="utf-8"))
    return {m: ModelPrice(prompt=p["prompt"], completion=p["completion"],
                          input_cache_read=p.get("input_cache_read"))
            for m, p in data.get("models", {}).items()}


def tokens_of(usage: dict | None) -> tuple[int, int]:
    usage = usage or {}
    return int(usage.get("prompt_tokens") or 0), int(usage.get("completion_tokens") or 0)


def cost_from_usage(model: str, usage: dict | None) -> tuple[float, str]:
    """-> (cost_usd, source) where source is 'provider', 'price_table', 'unknown' or 'none'."""
    if not usage:
        return 0.0, "none"
    c = usage.get("cost")
    if isinstance(c, (int, float)) and not isinstance(c, bool):
        return float(c), "provider"
    price = load_prices().get(model)
    if price is None:
        return 0.0, "unknown"
    pt, ct = tokens_of(usage)
    cached = int((usage.get("prompt_tokens_details") or {}).get("cached_tokens") or 0)
    cached = min(cached, pt)
    read_price = price.input_cache_read if price.input_cache_read is not None else price.prompt
    return (pt - cached) * price.prompt + cached * read_price + ct * price.completion, "price_table"


def estimate_cost(model: str, prompt_tokens: int, completion_tokens: int) -> float | None:
    price = load_prices().get(model)
    if price is None:
        return None
    return prompt_tokens * price.prompt + completion_tokens * price.completion
